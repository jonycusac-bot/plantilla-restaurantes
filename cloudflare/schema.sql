CREATE TABLE IF NOT EXISTS restaurant_state (id INTEGER PRIMARY KEY CHECK(id=1),revision INTEGER NOT NULL DEFAULT 1,payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS restaurant_images (id TEXT PRIMARY KEY,mime TEXT NOT NULL,bytes BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS restaurant_sessions (token TEXT PRIMARY KEY,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS restaurant_attempts (id TEXT PRIMARY KEY,count INTEGER NOT NULL,expires INTEGER NOT NULL);
